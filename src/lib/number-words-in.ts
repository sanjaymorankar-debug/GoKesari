/** Recogniser spelling variants folded together. */
export function normaliseDevanagari(word: string): string {
  return word.normalize("NFC").replace(/़/g, "").replace(/ँ/g, "ं").replace(/ऱ/g, "र");
}

const TABLE: Map<string, number> = (() => {
  const m = new Map<string, number>();
  const add = (w: string, n: number) => {
    const k = normaliseDevanagari(w);
    if (!m.has(k)) m.set(k, n);
    if (k.endsWith("न्न")) m.set(k.slice(0, -2), n); // अठ्ठावन्न → अठ्ठावन
  };
  HINDI.forEach((w, i) => add(w, i + 1));
  MARATHI.forEach((w, i) => add(w, i + 1));
  // Common alternative spellings.
  for (const [w, n] of [["पाँच", 5], ["छः", 6], ["छे", 6], ["नव", 9], ["अट्ठावन्न", 58], ["सत्तावण", 57], ["छपन्न", 56], ["पंचावन", 55]] as const) add(w, n);
  return m;
})();

/** A Hindi / Marathi number word 1–100, or null. */
export function indianNumberWord(word: string): number | null {
  return TABLE.get(normaliseDevanagari(word)) ?? null;
}
