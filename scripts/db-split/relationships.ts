/**
 * Writes docs/db-split-2026-10/RELATIONSHIPS.md from a database's real foreign
 * keys: which database owns each table, and every relationship that crosses
 * the two databases (enforced in the service layer after the split).
 *
 *   SOURCE_DATABASE_URL=postgresql://localhost/... npx tsx scripts/db-split/relationships.ts
 */
import { writeFileSync } from "node:fs";

import { connect, crossDbReferences, listForeignKeys, publicTables, splitTables } from "../../src/server/db/split/tools";

async function main() {
  const url = process.env.SOURCE_DATABASE_URL;
  if (!url) throw new Error("SOURCE_DATABASE_URL is not set.");
  const sql = connect(url, 1);
  try {
    const tables = splitTables(await publicTables(sql));
    const fks = await listForeignKeys(sql);
    const cross = crossDbReferences(fks);
    const byParent = (side: "seller" | "customer") => cross.filter((c) => c.to === side);
    const row = (c: (typeof cross)[number]) => `| ${c.table} | ${c.columns.join(", ")} | ${c.refTable}.${c.refColumns.join(", ")} | ${c.definition.match(/ON DELETE (\w+( \w+)?)/)?.[1] ?? "NO ACTION"} |`;
    const md = [
      "# Seller / customer split — table ownership and cross-database relationships",
      "",
      "Generated by `scripts/db-split/relationships.ts` from the database's real foreign keys. Do not edit by hand.",
      "",
      `- Seller database (gokesari_seller): **${tables.seller.length} tables** (${tables.seller.filter((t) => t.startsWith("pmd.")).length} of them the product-master schema \`pmd\`)`,
      `- Customer database (gokesari_customer, also the platform core): **${tables.customer.length} tables**`,
      `- Foreign keys: ${fks.length}, of which **${cross.length} cross the two databases**. PostgreSQL can't enforce those, so each becomes a service-layer check (\`src/server/db/split/integrity.ts\`) and is verified by \`scripts/db-split/run.ts verify\` (missing parents per link).`,
      "",
      "Shared keys are the stable UUIDs (`shop_id`, `shop_product_id`, `product_id`, `order_id`, `user_id`); none of them changes in the split.",
      "",
      "## Customer → seller (orders, carts, invoices… pointing at shops and products)",
      "",
      "| Child table (customer DB) | Column | → Parent (seller DB) | On delete (today) |",
      "|---|---|---|---|",
      ...byParent("seller").map(row),
      "",
      "## Seller → customer/core (shops, catalogue, KYC… pointing at users, orders, payments)",
      "",
      "| Child table (seller DB) | Column | → Parent (customer/core DB) | On delete (today) |",
      "|---|---|---|---|",
      ...byParent("customer").map(row),
      "",
      "## Tables per database",
      "",
      `**Seller:** ${tables.seller.map((t) => `\`${t}\``).join(", ")}`,
      "",
      `**Customer / core:** ${tables.customer.map((t) => `\`${t}\``).join(", ")}`,
      "",
    ].join("\n");
    writeFileSync("docs/db-split-2026-10/RELATIONSHIPS.md", md);
    console.log(`Wrote docs/db-split-2026-10/RELATIONSHIPS.md (${cross.length} cross-database relationships).`);
  } finally {
    await sql.end();
  }
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
