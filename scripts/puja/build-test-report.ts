/**
 * Writes the Puja Samagri testing report (Markdown + Excel) from
 * docs/puja-samagri-2026-11/test-results.json: pass / fail per test case on the local
 * database, test.gokesari.com and gokesari.com, with IST times, evidence and defects.
 *   node --import tsx scripts/puja/build-test-report.ts [outDir]
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import ExcelJS from "exceljs";

type Result = { status: string; at: string | null; evidence: string };
type Case = { id: string; area: string; title: string; how: Record<"local" | "test" | "prod", string>; results: Record<"local" | "test" | "prod", Result> };
type Defect = { id: string; found: string; where: string; summary: string; fix: string; status: string };
type Data = { title: string; pr: number; cases: Case[]; defects: Defect[]; notes?: string[]; screenshots?: { role: string; file: string; note: string }[] };

const ROOT = path.resolve(__dirname, "../..");
const DOCS = path.join(ROOT, "docs/puja-samagri-2026-11");
const data = JSON.parse(readFileSync(path.join(DOCS, "test-results.json"), "utf8")) as Data;
const outDir = process.argv[2] ?? DOCS;
const SITES = [
  ["local", "Local (PostgreSQL 18)"],
  ["test", "Test (test.gokesari.com)"],
  ["prod", "Prod (gokesari.com)"],
] as const;

function counts(site: "local" | "test" | "prod") {
  const by = new Map<string, number>();
  for (const c of data.cases) by.set(c.results[site].status, (by.get(c.results[site].status) ?? 0) + 1);
  return [...by].map(([s, n]) => `${s} ${n}`).join(", ");
}

function markdown(): string {
  const lines = [
    `# ${data.title}`,
    "",
    `PR #${data.pr} · all times IST · generated by scripts/puja/build-test-report.ts`,
    "",
    "## Summary",
    "",
    "| Site | Results |",
    "|---|---|",
    ...SITES.map(([k, label]) => `| ${label} | ${counts(k)} |`),
    "",
    "## Test cases",
    "",
    "| ID | Area | Test | Local | Test site | Prod |",
    "|---|---|---|---|---|---|",
    ...data.cases.map((c) => `| ${c.id} | ${c.area} | ${c.title} | ${c.results.local.status} | ${c.results.test.status} | ${c.results.prod.status} |`),
    "",
    "## How each was tested and the evidence",
    "",
    ...data.cases.flatMap((c) => [
      `### ${c.id} — ${c.title}`,
      ...SITES.map(([k, label]) => {
        const r = c.results[k];
        return `- **${label}:** ${r.status}${r.at ? ` (${r.at})` : ""} — ${c.how[k]}${r.evidence ? `. Evidence: ${r.evidence}` : ""}`;
      }),
      "",
    ]),
    "## Defects found and fixed",
    "",
    "| ID | Found | Where | Defect | Fix | Status |",
    "|---|---|---|---|---|---|",
    ...data.defects.map((d) => `| ${d.id} | ${d.found} | ${d.where} | ${d.summary} | ${d.fix} | ${d.status} |`),
    "",
    ...(data.screenshots?.length
      ? ["## Screenshots", "", ...data.screenshots.map((s) => `- **${s.role}:** \`${s.file}\` — ${s.note}`), ""]
      : []),
    ...(data.notes?.length ? ["## Open issues and notes", "", ...data.notes.map((n) => `- ${n}`), ""] : []),
  ];
  return lines.join("\n");
}

async function workbook(file: string): Promise<void> {
  const wb = new ExcelJS.Workbook();
  wb.creator = "GoKesari";
  const ws = wb.addWorksheet("Results", { views: [{ state: "frozen", ySplit: 1 }] });
  ws.addRow(["ID", "Area", "Test", "Local", "Local time (IST)", "Test site", "Test time (IST)", "Prod", "Prod time (IST)", "How on Test", "Evidence (Test)", "How on Prod", "Evidence (Prod)"]).font = { bold: true };
  const fill: Record<string, string> = { Pass: "FFC6EFCE", "Pass (partial)": "FFE2EFDA", Fail: "FFFFC7CE", Blocked: "FFF8CBAD", Running: "FFFFF2CC", "Not run": "FFEDEDED" };
  for (const c of data.cases) {
    const r = ws.addRow([
      c.id, c.area, c.title, c.results.local.status, c.results.local.at ?? "", c.results.test.status, c.results.test.at ?? "",
      c.results.prod.status, c.results.prod.at ?? "", c.how.test, c.results.test.evidence, c.how.prod, c.results.prod.evidence,
    ]);
    for (const col of [4, 6, 8]) {
      const v = String(r.getCell(col).value);
      r.getCell(col).fill = { type: "pattern", pattern: "solid", fgColor: { argb: fill[v] ?? "FFFFFFFF" } };
    }
    r.alignment = { wrapText: true, vertical: "top" };
  }
  [12, 14, 46, 12, 20, 12, 20, 12, 20, 30, 40, 30, 40].forEach((w, i) => (ws.getColumn(i + 1).width = w));
  const d = wb.addWorksheet("Defects");
  d.addRow(["ID", "Found (IST)", "Where", "Defect", "Fix", "Status"]).font = { bold: true };
  for (const x of data.defects) d.addRow([x.id, x.found, x.where, x.summary, x.fix, x.status]).alignment = { wrapText: true, vertical: "top" };
  [12, 22, 18, 50, 50, 18].forEach((w, i) => (d.getColumn(i + 1).width = w));
  const s = wb.addWorksheet("Summary");
  s.addRow(["Site", "Results"]).font = { bold: true };
  for (const [k, label] of SITES) s.addRow([label, counts(k)]);
  s.getColumn(1).width = 28;
  s.getColumn(2).width = 60;
  await wb.xlsx.writeFile(file);
}

async function main(): Promise<void> {
  writeFileSync(path.join(outDir, "TEST_REPORT.md"), markdown());
  await workbook(path.join(outDir, "PUJA_SAMAGRI_TEST_RESULTS_2026-11-20.xlsx"));
  console.log(`Wrote ${outDir}/TEST_REPORT.md and PUJA_SAMAGRI_TEST_RESULTS_2026-11-20.xlsx (${data.cases.length} cases)`);
}

void main();
