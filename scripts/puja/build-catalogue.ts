/**
 * Builds the Puja Samagri catalogue deliverables from src/server/puja/catalogue-data.ts:
 *   - the catalogue migration, PUJA_SEED_FILE in src/server/puja/seed-runner.ts (idempotent seed: shop type, categories,
 *     product types, products, Hindi/Marathi names + synonyms, catalogue flags)
 *   - docs/puja-samagri-2026-11/puja-samagri-catalogue.csv and .xlsx
 *   - public/images/puja/<category>.svg (generic placeholder per category)
 *
 * Run: node --import tsx scripts/puja/build-catalogue.ts
 * Re-running rewrites the files from the data; the SQL itself is safe to run any number of
 * times (every insert skips rows that already exist, matched by slug / key).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

import ExcelJS from "exceljs";

import { PUJA_CATEGORIES, PUJA_FESTIVALS, PUJA_SHOP_TYPE_KEY, PUJA_TYPES, pujaCatalogue, pujaTypeSlug, pujaCategoryImage } from "../../src/server/puja/catalogue";
import { PUJA_SEED_FILE } from "../../src/server/puja/seed-runner";

const ROOT = path.resolve(__dirname, "../..");
const DOCS = path.join(ROOT, "docs/puja-samagri-2026-11");
const IMAGES = path.join(ROOT, "public/images/puja");

const q = (v: string | null | undefined) => (v == null ? "NULL" : `'${v.replace(/'/g, "''")}'`);
const n = (v: number | null | undefined) => (v == null ? "NULL" : String(v));
const b = (v: boolean) => (v ? "true" : "false");
const arr = (v: readonly string[]) => (v.length ? `ARRAY[${v.map(q).join(", ")}]::text[]` : "ARRAY[]::text[]");

const rows = pujaCatalogue();

/* ------------------------------------------------------------------ SQL */
function buildSql(): string {
  const out: string[] = [];
  out.push(`-- Puja Samagri & Temple Supplies: master catalogue seed (owner brief, 20-Nov-2026).
-- GENERATED by scripts/puja/build-catalogue.ts from src/server/puja/catalogue-data.ts — do not edit by hand.
-- ${PUJA_CATEGORIES.length} categories, ${PUJA_TYPES.length} product types, ${rows.length} SKUs.
-- Idempotent: every insert skips what already exists (shop type by key, categories / product
-- types / products by slug, names and flags by product), so running it again adds nothing and
-- never overwrites an admin's later edits. Rollback: scripts/rollback-0152.sql.`);

  const goods = ["Agarbatti", "dhoop", "kapur", "candles", "diye", "havan samagri", "kumkum", "puja thali", "murti", "shringar", "flowers", "prasad", "mala", "puja kits", "festival items", "religious books", "temple bulk supplies"];
  out.push(`INSERT INTO "shop_types" ("key", "label", "standard_goods", "is_food", "status")
VALUES (${q(PUJA_SHOP_TYPE_KEY)}, 'Puja Samagri & Temple Supplies', ${arr(goods)}, false, 'ACTIVE')
ON CONFLICT DO NOTHING;`);

  const catValues = PUJA_CATEGORIES.map(
    (c) => `  (${q(c.en)}, ${q(c.slug)}, ${q(`${c.en} — ${c.hi} / ${c.mr}`)}, ${q(pujaCategoryImage(c.slug))}, ${c.no})`,
  ).join(",\n");
  // A live category elsewhere may already use the same name (names are unique site-wide):
  // then this one is called "<name> (Puja)".
  out.push(`INSERT INTO "product_categories" ("department", "name", "slug", "description", "image_url", "sort_order")
SELECT ${q(PUJA_SHOP_TYPE_KEY)},
       CASE WHEN EXISTS (SELECT 1 FROM "product_categories" x WHERE lower(x."name") = lower(v.name) AND x."deleted_at" IS NULL)
            THEN v.name || ' (Puja)' ELSE v.name END,
       v.slug, v.descr, v.img, v.sort
FROM (VALUES
${catValues}
) AS v(name, slug, descr, img, sort)
WHERE NOT EXISTS (SELECT 1 FROM "product_categories" c WHERE c."slug" = v.slug)
ON CONFLICT DO NOTHING;`);

  const typeValues = PUJA_TYPES.map((t, i) => {
    const cat = PUJA_CATEGORIES.find((c) => c.no === t.cat)!;
    const loose = rows.some((r) => r.typeKey === t.key && r.loose);
    const perishable = rows.some((r) => r.typeKey === t.key && r.perishable);
    const edible = rows.filter((r) => r.typeKey === t.key).every((r) => r.edible) && rows.some((r) => r.typeKey === t.key);
    const unit = rows.find((r) => r.typeKey === t.key)?.sellUnit ?? "pcs";
    return `  (${q(cat.slug)}, ${q(t.en)}, ${q(pujaTypeSlug(t.key))}, ${i + 1}, ${q(t.hi)}, ${q(t.mr)}, ${q(unit)}, ${b(loose)}, ${b(perishable)}, ${b(edible)})`;
  }).join(",\n");
  out.push(`INSERT INTO "product_subcategories" ("category_id", "name", "slug", "sort_order", "name_hi", "name_mr", "default_unit", "is_loose", "is_perishable", "is_edible")
SELECT c."id", v.name, v.slug, v.sort, v.hi, v.mr, v.unit, v.loose, v.perishable, v.edible
FROM (VALUES
${typeValues}
) AS v(cat_slug, name, slug, sort, hi, mr, unit, loose, perishable, edible)
JOIN "product_categories" c ON c."slug" = v.cat_slug
WHERE NOT EXISTS (SELECT 1 FROM "product_subcategories" s WHERE s."slug" = v.slug)
ON CONFLICT DO NOTHING;`);

  const productValues = rows
    .map(
      (r) =>
        `  (${q(r.categorySlug)}, ${q(r.typeSlug)}, ${q(r.nameEn)}, ${q(r.slug)}, ${q(r.description)}, ${q(r.imageUrl)}, ${q(r.loose ? "LOOSE" : "PACKAGED")}, ${q(r.variant)}, ${n(r.mrpPaise)}, ${q(r.hsnCode)}, ${r.gstRateBp}, ${n(r.netQuantity)}, ${q(r.netQuantityUnit)}, ${q(r.unit)})`,
    )
    .join(",\n");
  out.push(`INSERT INTO "products" ("category_id", "subcategory_id", "name", "slug", "description", "image_url", "kind", "variant", "mrp_paise", "mrp_source", "hsn_code", "gst_rate_bp", "net_quantity", "net_quantity_unit", "unit", "unit_size_milli", "subscribable", "is_active", "approval_status")
SELECT c."id", s."id", v.name, v.slug, v.descr, v.img, v.kind::product_kind, v.variant, v.mrp::bigint,
       CASE WHEN v.mrp IS NULL THEN NULL ELSE 'ADMIN'::mrp_source END,
       v.hsn, v.gst::integer, v.netq::integer, v.netu::text, v.unit, 1000, false, true, 'APPROVED'
FROM (VALUES
${productValues}
) AS v(cat_slug, type_slug, name, slug, descr, img, kind, variant, mrp, hsn, gst, netq, netu, unit)
JOIN "product_categories" c ON c."slug" = v.cat_slug
LEFT JOIN "product_subcategories" s ON s."slug" = v.type_slug
WHERE NOT EXISTS (SELECT 1 FROM "products" p WHERE p."slug" = v.slug)
ON CONFLICT DO NOTHING;`);

  const nameValues = rows
    .map((r) => `  (${q(r.slug)}, ${q(r.nameHi)}, ${q(r.nameMr)}, ${arr(r.synonyms)})`)
    .join(",\n");
  // search_text is built here from the names (the same expression the admin edit uses,
  // src/server/puja/search.ts LOCAL_SEARCH_TEXT_SQL).
  out.push(`INSERT INTO "product_local_names" ("product_id", "name_hi", "name_mr", "synonyms", "search_text")
SELECT p."id", v.hi, v.mr, v.syn,
       lower(concat_ws(' | ', p."name", v.hi, v.mr, s."name", s."name_hi", s."name_mr", array_to_string(v.syn, ' | ')))
FROM (VALUES
${nameValues}
) AS v(slug, hi, mr, syn)
JOIN "products" p ON p."slug" = v.slug
LEFT JOIN "product_subcategories" s ON s."id" = p."subcategory_id"
ON CONFLICT ("product_id") DO NOTHING;`);

  const attrValues = rows
    .map(
      (r) =>
        `  (${q(r.slug)}, ${q(r.sellUnit)}, ${b(r.perishable)}, ${b(r.edible)}, ${arr(r.festivals)}, ${q(JSON.stringify(r.variantAttrs))})`,
    )
    .join(",\n");
  out.push(`INSERT INTO "product_catalogue_attrs" ("product_id", "catalogue", "sell_unit", "is_perishable", "is_edible", "festivals", "variant_attrs", "tax_to_verify")
SELECT p."id", ${q(PUJA_SHOP_TYPE_KEY)}, v.unit, v.perishable, v.edible, v.fest, v.attrs::jsonb, true
FROM (VALUES
${attrValues}
) AS v(slug, unit, perishable, edible, fest, attrs)
JOIN "products" p ON p."slug" = v.slug
ON CONFLICT ("product_id") DO NOTHING;`);

  return out.join("\n--> statement-breakpoint\n") + "\n";
}

/* ------------------------------------------------------------ CSV / XLSX */
const HEADERS = [
  "SKU key (slug)", "Category no.", "Category", "Product type", "Name (English)", "Name (Hindi)", "Name (Marathi)",
  "Variant", "Search synonyms", "Unit", "Net qty", "Net unit", "Default MRP (₹)", "Loose", "Perishable", "Edible",
  "HSN code", "GST %", "HSN/GST status", "Festivals", "Brand", "Variant attributes", "Placeholder image",
];

function sheetRows(): (string | number | null)[][] {
  return rows.map((r) => [
    r.slug, r.categoryNo, r.categoryEn, r.typeEn, r.nameEn, r.nameHi, r.nameMr, r.variant, r.synonyms.join("; "),
    r.sellUnit, r.netQuantity, r.netQuantityUnit, r.mrpPaise == null ? null : r.mrpPaise / 100,
    r.loose ? "Yes" : "No", r.perishable ? "Yes" : "No", r.edible ? "Yes" : "No", r.hsnCode, r.gstRateBp / 100,
    "To verify with CA", r.festivals.join("; "), r.brand,
    Object.entries(r.variantAttrs).map(([k, v]) => `${k}: ${v}`).join("; "), r.imageUrl,
  ]);
}

function csvCell(v: string | number | null): string {
  if (v == null) return "";
  const s = String(v);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

async function writeWorkbook(file: string): Promise<void> {
  const wb = new ExcelJS.Workbook();
  wb.creator = "GoKesari";
  const ws = wb.addWorksheet("Puja catalogue", { views: [{ state: "frozen", ySplit: 1 }] });
  ws.addRow(HEADERS);
  for (const r of sheetRows()) ws.addRow(r);
  ws.getRow(1).font = { bold: true };
  ws.autoFilter = { from: "A1", to: `W${rows.length + 1}` };
  ws.columns.forEach((col, i) => {
    col.width = [34, 8, 26, 24, 40, 40, 40, 22, 50, 7, 8, 8, 12, 7, 9, 7, 11, 7, 18, 24, 12, 40, 36][i] ?? 14;
  });

  const cats = wb.addWorksheet("Categories");
  cats.addRow(["No.", "Category (English)", "Hindi", "Marathi", "Slug", "SKUs"]);
  for (const c of PUJA_CATEGORIES) cats.addRow([c.no, c.en, c.hi, c.mr, c.slug, rows.filter((r) => r.categoryNo === c.no).length]);
  cats.addRow([]);
  cats.addRow(["", "Total", "", "", "", rows.length]);
  cats.getRow(1).font = { bold: true };
  cats.columns.forEach((col, i) => (col.width = [6, 34, 30, 30, 30, 8][i]));

  const types = wb.addWorksheet("Product types");
  types.addRow(["Category no.", "Product type", "Hindi", "Marathi", "Slug", "SKUs"]);
  for (const t of PUJA_TYPES) types.addRow([t.cat, t.en, t.hi, t.mr, pujaTypeSlug(t.key), rows.filter((r) => r.typeKey === t.key).length]);
  types.getRow(1).font = { bold: true };
  types.columns.forEach((col, i) => (col.width = [8, 32, 30, 30, 30, 8][i]));

  const fest = wb.addWorksheet("Festivals");
  fest.addRow(["Key", "English", "Hindi", "Marathi", "Tagged SKUs"]);
  for (const f of PUJA_FESTIVALS) fest.addRow([f.key, f.en, f.hi, f.mr, rows.filter((r) => r.festivals.includes(f.key)).length]);
  fest.getRow(1).font = { bold: true };
  fest.columns.forEach((col, i) => (col.width = [20, 26, 24, 24, 12][i]));

  const notes = wb.addWorksheet("Notes");
  for (const line of [
    "GoKesari — Puja Samagri & Temple Supplies master catalogue",
    `Generated from src/server/puja/catalogue-data.ts: ${rows.length} SKUs, ${PUJA_CATEGORIES.length} categories, ${PUJA_TYPES.length} product types.`,
    "Default MRP: a typical retail MRP where one is common; blank where it varies by brand or the item is sold loose (the shop sets the price).",
    "Every HSN code and GST rate is a best reading of the schedules after the Sept-2025 GST rate change and is marked 'To verify with CA' in the admin view.",
    "Loose goods have no MRP and show 'Price on confirmation' to customers until the shop sets a price.",
    "Edible lines (category 10 and the edible kits / bulk lines) need FSSAI while the admin's FSSAI toggle is on.",
    "Images: one generic placeholder per category; shops upload real photos.",
  ]) notes.addRow([line]);
  notes.getColumn(1).width = 140;
  await wb.xlsx.writeFile(file);
}

/* ---------------------------------------------------------------- images */
const PALETTE = ["#F57C00", "#E65100", "#FB8C00", "#D84315", "#C62828", "#AD1457", "#6A1B9A", "#4527A0", "#2E7D32", "#EF6C00", "#5D4037", "#F9A825", "#00838F", "#283593", "#37474F"];

function placeholderSvg(no: number, en: string): string {
  const colour = PALETTE[(no - 1) % PALETTE.length];
  const words = en.replace(/\s*\(.*\)/, "").split(/\s+/);
  const lines: string[] = [];
  for (const w of words) {
    const last = lines[lines.length - 1];
    if (last && (last + " " + w).length <= 16) lines[lines.length - 1] = last + " " + w;
    else lines.push(w);
  }
  const text = lines
    .slice(0, 3)
    .map((l, i) => `<text x="200" y="${292 + i * 34}" text-anchor="middle" font-family="system-ui, sans-serif" font-size="28" font-weight="600" fill="#fff">${l.replace(/&/g, "&amp;")}</text>`)
    .join("");
  // A diya: bowl, flame and a soft glow — the same mark for every category, in its own colour.
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 400 400" role="img" aria-label="${en.replace(/&/g, "&amp;")}">
<rect width="400" height="400" rx="32" fill="${colour}"/>
<circle cx="200" cy="140" r="78" fill="#fff" opacity="0.12"/>
<path d="M200 70c22 30 30 52 18 72-6 10-14 14-18 14s-12-4-18-14c-12-20-4-42 18-72z" fill="#FFE082"/>
<path d="M200 102c10 15 13 26 7 36-3 5-6 7-7 7s-4-2-7-7c-6-10-3-21 7-36z" fill="#FF7043"/>
<path d="M118 176h164c0 40-37 64-82 64s-82-24-82-64z" fill="#FFF3E0"/>
<rect x="150" y="238" width="100" height="10" rx="5" fill="#FFF3E0" opacity="0.8"/>
${text}
</svg>
`;
}

async function main(): Promise<void> {
  mkdirSync(DOCS, { recursive: true });
  mkdirSync(IMAGES, { recursive: true });
  writeFileSync(path.join(ROOT, PUJA_SEED_FILE), buildSql());
  const csv = [HEADERS, ...sheetRows()].map((r) => r.map(csvCell).join(",")).join("\n") + "\n";
  writeFileSync(path.join(DOCS, "puja-samagri-catalogue.csv"), "﻿" + csv);
  await writeWorkbook(path.join(DOCS, "puja-samagri-catalogue.xlsx"));
  for (const c of PUJA_CATEGORIES) writeFileSync(path.join(IMAGES, `${c.slug}.svg`), placeholderSvg(c.no, c.en));
  console.log(`Wrote ${rows.length} SKUs: ${PUJA_SEED_FILE}, docs/puja-samagri-2026-11/puja-samagri-catalogue.{csv,xlsx}, ${PUJA_CATEGORIES.length} images.`);
}

