qa("TC-SUB-013", "a subscription order carries the drop address (and society) like a checkout order, and gets a settlement snapshot at DELIVERED", async () => {
  const g = generated();
  if (!unstash<boolean>(`${KEY}-delivered`)) blocked("needs the delivery of TC-SUB-018");
  const order = await orderOf("customer", g.orderId);
  const problems: string[] = [];
  if (!order?.deliveryAddressSnapshot) problems.push("the order has no delivery address snapshot: the subscribe page (src/components/subscribe-form.tsx) sends no addressId and generateOneDelivery (src/server/services/subscriptions.ts) does not fall back to the customer's default address, so the rider gets no drop address");
  const [fin] = await db()`select count(*)::int as n from order_financials where order_id = ${g.orderId}`;
  if (fin.n !== 1) problems.push("no settlement snapshot at DELIVERED");
  expect(problems, `${problems.join("; ")} (order ${order?.orderNumber}, society ${order?.societyId ?? "none"})`).toEqual([]);
  return `${order?.orderNumber}: address ${JSON.stringify(order?.deliveryAddressSnapshot).slice(0, 80)}; society ${order?.societyId ?? "none"}; settlement snapshot written`;
}, { ...local, partial: "the customer's address in this world is not linked to a society, so the society half shows 'none'" });

